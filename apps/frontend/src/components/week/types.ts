/** Одна неделя в сетке календаря. */
export interface Week {
  /** Номер недели (передаётся наверх при выборе). */
  index: number;
  /** Первый день недели. */
  start: Date;
  /** Последний день недели. */
  end: Date;
  /** Произвольная подпись периода (переопределяет расчёт по датам). */
  label?: string;
}
